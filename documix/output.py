"""Writers for the generated document. The literal strings are part of the
output contract (tests and downstream consumers depend on them)."""
import datetime
import os

from . import textutils


def write_standard_preamble(out, source_dir, total_files, structure):
    """Write the Repomix-like summary, directory info and directory tree."""
    out.write("This file is a merged representation of all documents, combined into a single document.\n\n")

    out.write("# File Summary\n\n")
    out.write("## Purpose\n")
    out.write("This file contains a packed representation of the entire directory's contents.\n")
    out.write("It is designed to be easily consumable by AI systems for analysis, review,\n")
    out.write("or other automated processes.\n\n")

    out.write("## File Format\n")
    out.write("The content is organized as follows:\n")
    out.write("1. This summary section\n")
    out.write("2. Directory information\n")
    out.write("3. Directory structure\n")
    out.write("4. Multiple file entries, each consisting of:\n")
    out.write("  a. A header with the file path (## File: path/to/file)\n")
    out.write("  b. The full contents of the file: converted documents as Markdown, text and code files in a code block\n\n")

    out.write("## Usage Guidelines\n")
    out.write("- This file should be treated as read-only. Any changes should be made to the\n")
    out.write("  original files, not this packed version.\n")
    out.write("- When processing this file, use the file path to distinguish\n")
    out.write("  between different files in the directory.\n\n")

    out.write("## Notes\n")
    out.write("- Some files may have been excluded based on extension filters or exclusion patterns\n")
    out.write("- Binary files are only partially supported (PDF, EPUB, DOCX) and conversion quality may vary\n")
    out.write("- ZIP files are automatically extracted and their contents are included\n")
    out.write("- Email files (.eml) are parsed with attachments processed from local folders if available\n")
    out.write("- Files matching specified exclude patterns are skipped\n\n")

    out.write("# Directory Information\n")
    out.write(f"- Source Directory: {source_dir}\n")
    out.write(f"- Compilation Date: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
    out.write(f"- Total Files Processed: {total_files}\n\n")

    out.write("# Directory Structure\n")
    out.write("```\n")
    for item in structure:
        out.write(f"{item}\n")
    out.write("```\n\n")

    out.write("# Files\n\n")


def write_file_entry(out, rel_path, method, content, language, fenced):
    """Write one file section. Markdown content goes in raw; text/code files
    are wrapped in a four-backtick block (Repomix compatible)."""
    out.write(f"## File: {rel_path} (converted with {method})\n")
    if not fenced:
        out.write(content)
        if not content.endswith("\n"):
            out.write("\n")
        out.write("\n")
        return
    backticks = "````"
    if language:
        out.write(f"{backticks}{language}\n")
    else:
        out.write(f"{backticks}\n")
    out.write(content)
    out.write(f"\n{backticks}\n\n")


def write_single_email(out_file, version, email_info, content):
    """Format output for single email mode."""
    out_file.write("# Email Analysis Report\n\n")
    out_file.write(f"Generated by DocuMix v{version} on {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
    out_file.write("Processing mode: Single Email\n\n")

    out_file.write("## Email Summary\n\n")
    out_file.write("This document contains a complete analysis of an email message, including:\n")
    out_file.write("- Full email headers and metadata\n")
    out_file.write("- Converted email body content (HTML → Markdown)\n")
    out_file.write("- Processed attachments with extracted content\n")
    out_file.write("- Communication context and authentication details\n\n")

    out_file.write("## Email Details\n\n")
    out_file.write("### Message Information\n")
    out_file.write(f"- **Subject**: {email_info.get('subject', 'No Subject')}\n")
    out_file.write(f"- **From**: {email_info.get('from', 'Unknown')}\n")
    out_file.write(f"- **To**: {email_info.get('to', 'Unknown')}\n")
    out_file.write(f"- **Date**: {email_info.get('date', 'Unknown')}\n")

    if email_info.get('cc'):
        out_file.write(f"- **CC**: {email_info['cc']}\n")

    total_size = email_info.get('size', 0) + sum(att.get('size', 0) for att in email_info.get('attachments', []))
    out_file.write(f"- **Size**: {textutils.format_size(total_size)}\n\n")

    # Authentication section if available
    if email_info.get('auth_results') or email_info.get('dkim_signature'):
        out_file.write("### Authentication & Security\n")
        if email_info.get('auth_results'):
            auth = email_info['auth_results']
            if 'spf=pass' in auth:
                out_file.write("- **SPF**: Pass\n")
            elif 'spf=fail' in auth:
                out_file.write("- **SPF**: Fail\n")

            if 'dkim=pass' in auth:
                out_file.write("- **DKIM**: Pass\n")
            elif 'dkim=fail' in auth:
                out_file.write("- **DKIM**: Fail\n")

            if 'dmarc=pass' in auth:
                out_file.write("- **DMARC**: Pass\n")
            elif 'dmarc=fail' in auth:
                out_file.write("- **DMARC**: Fail\n")
        out_file.write("\n")

    # Attachments summary
    attachments = email_info.get('attachments', [])
    if attachments:
        out_file.write("### Attachments Summary\n")
        out_file.write(f"- **Count**: {len(attachments)} files\n")
        total_att_size = sum(att.get('size', 0) for att in attachments)
        out_file.write(f"- **Total Size**: {textutils.format_size(total_att_size)}\n")

        types = {}
        for att in attachments:
            ext = os.path.splitext(att['filename'].lower())[1]
            types[ext] = types.get(ext, 0) + 1

        type_list = [f"{ext.upper()[1:]} ({count})" for ext, count in types.items()]
        out_file.write(f"- **Types**: {', '.join(type_list)}\n\n")

    out_file.write("## Email Content\n\n")
    out_file.write(content)
    out_file.write("\n\n")

    out_file.write("## Processing Notes\n")
    out_file.write("- HTML content converted to Markdown using html2text\n")
    if email_info.get('attachments_source'):
        out_file.write(f"- Attachments source: {email_info['attachments_source']}\n")
    out_file.write("\n")

    out_file.write("## Statistics\n")
    out_file.write(f"- Total characters: {len(content):,}\n")
    out_file.write(f"- Estimated tokens: {textutils.estimate_tokens(content):,}\n")
