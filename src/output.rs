//! Writers for the generated document; literals are copied from
//! `documix/output.py` and must stay byte-identical.
use std::io::Write;

use crate::textutils::{estimate_tokens, format_size, py_len, thousands};

pub fn now_stamp() -> String {
    chrono::Local::now().format("%Y-%m-%d %H:%M:%S").to_string()
}

pub fn write_standard_preamble<W: Write>(out: &mut W, source_dir: &str, total_files: usize, structure: &[String]) -> std::io::Result<()> {
    out.write_all(b"This file is a merged representation of all documents, combined into a single document.\n\n")?;
    out.write_all(b"# File Summary\n\n")?;
    out.write_all(b"## Purpose\n")?;
    out.write_all(b"This file contains a packed representation of the entire directory's contents.\n")?;
    out.write_all(b"It is designed to be easily consumable by AI systems for analysis, review,\n")?;
    out.write_all(b"or other automated processes.\n\n")?;
    out.write_all(b"## File Format\n")?;
    out.write_all(b"The content is organized as follows:\n")?;
    out.write_all(b"1. This summary section\n")?;
    out.write_all(b"2. Directory information\n")?;
    out.write_all(b"3. Directory structure\n")?;
    out.write_all(b"4. Multiple file entries, each consisting of:\n")?;
    out.write_all(b"  a. A header with the file path (## File: path/to/file)\n")?;
    out.write_all(b"  b. The full contents of the file: converted documents as Markdown, text and code files in a code block\n\n")?;
    out.write_all(b"## Usage Guidelines\n")?;
    out.write_all(b"- This file should be treated as read-only. Any changes should be made to the\n")?;
    out.write_all(b"  original files, not this packed version.\n")?;
    out.write_all(b"- When processing this file, use the file path to distinguish\n")?;
    out.write_all(b"  between different files in the directory.\n\n")?;
    out.write_all(b"## Notes\n")?;
    out.write_all(b"- Some files may have been excluded based on extension filters or exclusion patterns\n")?;
    out.write_all(b"- Binary files are only partially supported (PDF, EPUB, DOCX) and conversion quality may vary\n")?;
    out.write_all(b"- ZIP files are automatically extracted and their contents are included\n")?;
    out.write_all(b"- Email files (.eml) are parsed with attachments processed from local folders if available\n")?;
    out.write_all(b"- Files matching specified exclude patterns are skipped\n\n")?;
    out.write_all(b"# Directory Information\n")?;
    writeln!(out, "- Source Directory: {source_dir}")?;
    writeln!(out, "- Compilation Date: {}", now_stamp())?;
    writeln!(out, "- Total Files Processed: {total_files}\n")?;
    out.write_all(b"# Directory Structure\n")?;
    out.write_all(b"```\n")?;
    for item in structure {
        writeln!(out, "{item}")?;
    }
    out.write_all(b"```\n\n")?;
    out.write_all(b"# Files\n\n")?;
    Ok(())
}

pub fn write_file_entry<W: Write>(out: &mut W, rel_path: &str, method: &str, content: &str, language: &str, fenced: bool) -> std::io::Result<()> {
    writeln!(out, "## File: {rel_path} (converted with {method})")?;
    if !fenced {
        out.write_all(content.as_bytes())?;
        if !content.ends_with('\n') {
            out.write_all(b"\n")?;
        }
        out.write_all(b"\n")?;
        return Ok(());
    }
    if language.is_empty() {
        out.write_all(b"````\n")?;
    } else {
        writeln!(out, "````{language}")?;
    }
    out.write_all(content.as_bytes())?;
    out.write_all(b"\n````\n\n")?;
    Ok(())
}

pub struct EmailInfo {
    pub subject: String,
    pub from: String,
    pub to: String,
    pub cc: String,
    pub date: String,
    pub auth_results: String,
    pub dkim_signature: String,
    pub attachments_source: String,
    pub size: u64,
    /// (filename, size) per attachment.
    pub attachments: Vec<(String, u64)>,
}

pub fn write_single_email<W: Write>(out: &mut W, version: &str, info: &EmailInfo, content: &str) -> std::io::Result<()> {
    out.write_all(b"# Email Analysis Report\n\n")?;
    writeln!(out, "Generated by DocuMix v{version} on {}", now_stamp())?;
    out.write_all(b"Processing mode: Single Email\n\n")?;
    out.write_all(b"## Email Summary\n\n")?;
    out.write_all(b"This document contains a complete analysis of an email message, including:\n")?;
    out.write_all(b"- Full email headers and metadata\n")?;
    out.write_all("- Converted email body content (HTML → Markdown)\n".as_bytes())?;
    out.write_all(b"- Processed attachments with extracted content\n")?;
    out.write_all(b"- Communication context and authentication details\n\n")?;
    out.write_all(b"## Email Details\n\n")?;
    out.write_all(b"### Message Information\n")?;
    let or_default = |value: &str, default: &str| if value.is_empty() { default.to_string() } else { value.to_string() };
    writeln!(out, "- **Subject**: {}", or_default(&info.subject, "No Subject"))?;
    writeln!(out, "- **From**: {}", or_default(&info.from, "Unknown"))?;
    writeln!(out, "- **To**: {}", or_default(&info.to, "Unknown"))?;
    writeln!(out, "- **Date**: {}", or_default(&info.date, "Unknown"))?;
    if !info.cc.is_empty() {
        writeln!(out, "- **CC**: {}", info.cc)?;
    }
    let total_size = info.size + info.attachments.iter().map(|a| a.1).sum::<u64>();
    writeln!(out, "- **Size**: {}\n", format_size(total_size))?;

    if !info.auth_results.is_empty() || !info.dkim_signature.is_empty() {
        out.write_all(b"### Authentication & Security\n")?;
        if !info.auth_results.is_empty() {
            let auth = &info.auth_results;
            if auth.contains("spf=pass") {
                out.write_all(b"- **SPF**: Pass\n")?;
            } else if auth.contains("spf=fail") {
                out.write_all(b"- **SPF**: Fail\n")?;
            }
            if auth.contains("dkim=pass") {
                out.write_all(b"- **DKIM**: Pass\n")?;
            } else if auth.contains("dkim=fail") {
                out.write_all(b"- **DKIM**: Fail\n")?;
            }
            if auth.contains("dmarc=pass") {
                out.write_all(b"- **DMARC**: Pass\n")?;
            } else if auth.contains("dmarc=fail") {
                out.write_all(b"- **DMARC**: Fail\n")?;
            }
        }
        out.write_all(b"\n")?;
    }

    if !info.attachments.is_empty() {
        out.write_all(b"### Attachments Summary\n")?;
        writeln!(out, "- **Count**: {} files", info.attachments.len())?;
        let total: u64 = info.attachments.iter().map(|a| a.1).sum();
        writeln!(out, "- **Total Size**: {}", format_size(total))?;
        // Group by extension, preserving first-seen order like a Python dict.
        let mut types: Vec<(String, usize)> = Vec::new();
        for (name, _) in &info.attachments {
            let ext = crate::textutils::extension_of(&name.to_lowercase()).to_string();
            if let Some(entry) = types.iter_mut().find(|(e, _)| *e == ext) {
                entry.1 += 1;
            } else {
                types.push((ext, 1));
            }
        }
        let list: Vec<String> = types
            .iter()
            .map(|(ext, count)| {
                let upper = ext.to_uppercase();
                let shown = upper.chars().skip(1).collect::<String>();
                format!("{shown} ({count})")
            })
            .collect();
        writeln!(out, "- **Types**: {}\n", list.join(", "))?;
    }

    out.write_all(b"## Email Content\n\n")?;
    out.write_all(content.as_bytes())?;
    out.write_all(b"\n\n")?;
    out.write_all(b"## Processing Notes\n")?;
    out.write_all(b"- HTML content converted to Markdown using html2text\n")?;
    if !info.attachments_source.is_empty() {
        writeln!(out, "- Attachments source: {}", info.attachments_source)?;
    }
    out.write_all(b"\n")?;
    out.write_all(b"## Statistics\n")?;
    writeln!(out, "- Total characters: {}", thousands(py_len(content)))?;
    writeln!(out, "- Estimated tokens: {}", thousands(estimate_tokens(content)))?;
    Ok(())
}
