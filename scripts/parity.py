FIXTURES = os.path.join(PYTHON_DIR, 'tests', 'fixtures')

NORMALISE = [
    re.compile(r'^- Compilation Date: .*$'),
    re.compile(r'^Generated by DocuMix v.* on \d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$'),
    re.compile(r'^Generated by DocuMix on \d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$'),
    re.compile(r'^- Processing time: \d+\.\d{2}s$'),
]
ZIP_METHOD = re.compile(r'^(#{2,3} File: .* \(converted with zip_extract\+)([^)]*)(\).*)$')


def normalise(text):
    out = []
    for line in text.split('\n'):
        if any(rx.match(line) for rx in NORMALISE):
            out.append('<normalised>')
            continue
        m = ZIP_METHOD.match(line)
        if m:
            parts = '+'.join(sorted(m.group(2).split('+')))
            line = f'{m.group(1)}{parts}{m.group(3)}'
        out.append(line)
    return out


# ---------------------------------------------------------------- fixtures --

def write(path, data, binary=False):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'wb' if binary else 'w', encoding=None if binary else 'utf-8', newline=None if binary else '') as fh:
        fh.write(data)


def eml(headers, plain=None, html=None, attachments=(), crlf=True):
    nl = '\r\n' if crlf else '\n'
    lines = [f'{k}: {v}' for k, v in headers]
    lines.append('MIME-Version: 1.0')
    body_parts = []
    if plain is not None and html is not None:
        alt = ['Content-Type: multipart/alternative; boundary="ALT"', '', '--ALT',
               'Content-Type: text/plain; charset="utf-8"', '', plain, '--ALT',
               'Content-Type: text/html; charset="utf-8"', '', html, '--ALT--']
        body_parts.append(nl.join(alt))
    elif html is not None:
        body_parts.append(nl.join(['Content-Type: text/html; charset="utf-8"', '', html]))
    else:
        body_parts.append(nl.join(['Content-Type: text/plain; charset="utf-8"', '', plain or '']))
    for name, data, ctype in attachments:
        enc = base64.b64encode(data).decode()
        chunks = [enc[i:i + 76] for i in range(0, len(enc), 76)]
        body_parts.append(nl.join([f'Content-Type: {ctype}; name="{name}"', 'Content-Transfer-Encoding: base64',
                                   f'Content-Disposition: attachment; filename="{name}"', ''] + chunks))
    if len(body_parts) == 1 and not attachments:
        lines.append(body_parts[0])
        return nl.join(lines) + nl
    lines.append('Content-Type: multipart/mixed; boundary="MIX"')
    lines.append('')
    out = nl.join(lines) + nl
    for part in body_parts:
        out += '--MIX' + nl + part + nl
    out += '--MIX--' + nl
    return out


