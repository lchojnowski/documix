def run(cmd, cwd):
    proc = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, errors='replace')
    return proc


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--rust', default=os.path.join(REPO, 'target', 'release', 'documix'))
    ap.add_argument('--python', default=os.path.join(REPO, '.venv', 'bin', 'python'))
    ap.add_argument('--keep', action='store_true', help='keep the temp directory')
    ap.add_argument('--filter', default=None, help='substring of case names to run')
    args = ap.parse_args()
    if not os.path.exists(args.rust):
        print(f'Rust binary not found: {args.rust}', file=sys.stderr)
        return 2

    root = tempfile.mkdtemp(prefix='documix-parity-')
    fixtures = os.path.join(root, 'fixtures')
    cases = build_fixtures(fixtures)
    results = []
    for case in cases:
        if args.filter and args.filter not in case['name']:
            continue
        work = os.path.join(root, 'runs', re.sub(r'[^\w]+', '_', case['name']))
        verdict = compare_case(case, work, args)
        results.append((case['name'], verdict))
        status, detail = verdict
        print(f"{'PASS' if status else 'FAIL':4s} {case['name']:48s} {detail}")
    failed = [name for name, (ok, _) in results if not ok]
    print(f"\n{len(results) - len(failed)}/{len(results)} cases identical")
    if args.keep or failed:
        print(f'runs kept in {root}')
    else:
        shutil.rmtree(root, ignore_errors=True)
    return 1 if failed else 0


def compare_case(case, work, args):
    outputs = {}
    codes = {}
    shared = os.path.join(work, 'src')  # same path for both, so `Source Directory` matches
    for impl, cmd in (('py', [args.python, '-m', 'documix']), ('rs', [args.rust])):
        run_dir = os.path.join(work, impl)
        os.makedirs(run_dir, exist_ok=True)
        src = case['src']
        # Fresh copy per implementation (email processing mutates the tree),
        # always at the same path.
        shutil.rmtree(shared, ignore_errors=True)
        if os.path.isdir(src):
            shutil.copytree(src, shared, symlinks=True)
            target = shared
        elif os.path.isfile(src):
            shutil.copytree(os.path.dirname(src), shared, symlinks=True)
            target = os.path.join(shared, os.path.basename(src))
        else:
            target = src
        out = os.path.join(run_dir, 'out.md')
        # Both run from python/ (the package is importable from there; the Rust binary does not care).
        proc = run(cmd + [target] + case['args'] + ['-o', out], cwd=PYTHON_DIR)
        codes[impl] = proc.returncode
        with open(os.path.join(run_dir, 'stdout.txt'), 'w') as fh:
            fh.write(proc.stdout)
        with open(os.path.join(run_dir, 'stderr.txt'), 'w') as fh:
            fh.write(proc.stderr)
        outputs[impl] = open(out, 'rb').read().decode('utf-8', errors='replace') if os.path.exists(out) else None
    if codes['py'] != codes['rs']:
        return (False, f"exit codes differ: python {codes['py']} vs rust {codes['rs']}")
    if (outputs['py'] is None) != (outputs['rs'] is None):
        return (False, f"output file presence differs: python {outputs['py'] is not None} vs rust {outputs['rs'] is not None}")
    if outputs['py'] is None:
        return (True, f"exit {codes['py']}, no output file (both)")
    py_lines = normalise(outputs['py'])
    rs_lines = normalise(outputs['rs'])
    if py_lines == rs_lines:
        return (True, f"exit {codes['py']}, {len(outputs['py'])} bytes identical")
    for i, (a, b) in enumerate(zip(py_lines, rs_lines), 1):
        if a != b:
            return (False, f"first diff at line {i}: python {a[:70]!r} vs rust {b[:70]!r}")
    return (False, f"length differs: python {len(py_lines)} lines vs rust {len(rs_lines)} lines")


if __name__ == '__main__':
    sys.exit(main())
